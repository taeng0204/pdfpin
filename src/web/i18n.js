const DICTS = { en: EN, ko: KO };
export const LANGUAGE_NAMES = { auto: 'settings.languageAuto', en: 'English', ko: '한국어' };

let lang = 'en';

export function resolveLanguage(setting) {
  if (setting && setting !== 'auto') return DICTS[setting] ? setting : 'en';
  const nav = (navigator.languages?.[0] || navigator.language || 'en').toLowerCase();
  return nav.startsWith('ko') ? 'ko' : 'en';
}

export function setLanguage(setting) {
  lang = resolveLanguage(setting);
  document.documentElement.lang = lang;
  return lang;
}

export const currentLanguage = () => lang;

/** Look up a string. `{n}` picks the singular variant (key + "One") when n is 1. */
export function t(key, vars = {}) {
  let k = key;
  if (vars.n === 1 && DICTS[lang][`${key}One`]) k = `${key}One`;
  const raw = DICTS[lang][k] ?? DICTS.en[k] ?? DICTS.en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
}
